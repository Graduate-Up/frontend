import type { MajorCode } from '@/api/types'

/**
 * 요건별 채우는 방법 안내 (학부 공지 기준).
 * - options: 졸업요건 상세 오른쪽 '채우는 방법' 카드
 * - link: 이수 내역 → 비교과 입력 줄에 보여줄 신청 사이트
 * - guide: 졸업요건 상세 '내 기록' 아래 자세한 안내
 */
export type FillOption = {
  /** 라벨 자리에 쓸 기호 (예: ⓐ). 없으면 '방법 1 · 2 · 3' */
  mark?: string
  title: string
  sub: string
  /** 외부 신청 사이트 */
  url?: string
}

export type GuideSection = {
  /** 번호 대신 쓸 기호 (예: ⓐ) */
  mark?: string
  title: string
  /** 인정 기준 */
  body: string[]
  /** 제출할 증빙 */
  evidence?: string
  /** ※ 주의 */
  notes?: string[]
}

export type FillGuide = {
  /** 이 전공에만 보여준다 (없으면 모든 전공) */
  majors?: MajorCode[]
  options: FillOption[]
  link?: { label: string; url: string }
  guide?: {
    /** 안내를 놓을 곳 — main: '내 기록' 아래 (기본), side: 오른쪽 '채우는 방법' 아래 */
    placement?: 'main' | 'side'
    /** 안내 맨 위 한두 줄 */
    intro?: string[]
    title: string
    /** 제출 서류 */
    submit?: string
    sections: GuideSection[]
    /** 꼭 알아야 할 추가 안내 */
    warning?: { title: string; body: string[] }
  }
}

